"""Pure structural gate for a preregistered ABC-like correction; research only.

This is NOT a market entry signal, a full Elliott classifier, or Paper integration.
Causal OHLC pivot extraction, raw-path rejection and order execution are separate
future gates. A pivot with right bars must already be confirmed before this call.
"""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, InvalidOperation, localcontext
from typing import Sequence

RESEARCH_ONLY = True
LIVE_ENABLED = False
MARKET_EXECUTION_ENABLED = False
AUTOMATIC_FACTORY_REGISTRATION = False

WIDTH = 3
MAX_SPAN = 192
MAX_AGE = 32
B_MIN, B_MAX = Decimal("0.382"), Decimal("0.786")
C_MIN, C_MAX = Decimal("0.618"), Decimal("1.618")


@dataclass(frozen=True)
class ConfirmedABCPivot:
    kind: str
    index: int
    confirmed_at: int
    price: str | int | float | Decimal


def review_abc_corrective_shape(
    pivots: Sequence[ConfirmedABCPivot], decision_index: int,
) -> dict | None:
    """Review latest confirmed H-L-H-L, using no later pivot or future price.

    A separate streaming caller must prove each pivot from strict left/right
    completed OHLC, reject tied/dual extrema, preserve path identity, and
    consume the first eligible breakout even if any later cost/context gate
    rejects it. None of those market events are generated by this function.
    """
    if type(decision_index) is not int or decision_index < 0:
        raise ValueError("decision_index must be a nonnegative integer")
    if len(pivots) < 4:
        return None
    group = list(pivots)[-4:]
    if tuple(p.kind for p in group) != ("high", "low", "high", "low"):
        return None
    if any(type(p.index) is not int or type(p.confirmed_at) is not int
           or p.index < 0 or p.confirmed_at != p.index + WIDTH
           or p.confirmed_at >= decision_index for p in group):
        return None
    if any(b.index <= a.index for a, b in zip(group, group[1:])):
        return None
    if group[-1].index - group[0].index > MAX_SPAN:
        return None
    age = decision_index - group[-1].confirmed_at
    if not 1 <= age <= MAX_AGE:
        return None
    try:
        values = tuple(Decimal(str(p.price)) for p in group)
    except (InvalidOperation, ValueError, TypeError):
        return None
    if any(not p.is_finite() or p <= 0 for p in values):
        return None
    h0, la, hb, lc = values
    if not (h0 > hb > la > lc):
        return None
    with localcontext() as ctx:
        ctx.prec = 50
        denom = h0 - la
        if denom <= 0:
            return None
        b = (hb - la) / denom
        c = (hb - lc) / denom
        if not B_MIN <= b <= B_MAX or not C_MIN <= c <= C_MAX:
            return None
    return {
        "schema": "nexus.research-abc-correction-shape.v1",
        "identity": (group[0].index, group[-1].index),
        "H0": h0, "LA": la, "HB": hb, "LC": lc,
        "B_retracement": b, "C_extension": c,
        "confirmed_at": group[-1].confirmed_at,
        "earliest_decision_index": group[-1].confirmed_at + 1,
        "breakout_reference": hb, "invalidation_reference": lc,
        "full_recursive_elliott_classification": False,
        "trade_signal": False,
        "research_only": True,
        "live_enabled": False,
    }
